import type { Chapter, CloudShape, Decoration } from './types';

// Helper: generate cloud puffs
function cloud(x: number, y: number, w: number, speed: number): CloudShape {
  const puffs = [
    { dx: 0, dy: 0, r: w * 0.3 },
    { dx: -w * 0.2, dy: w * 0.05, r: w * 0.22 },
    { dx: w * 0.2, dy: w * 0.05, r: w * 0.22 },
    { dx: -w * 0.1, dy: -w * 0.12, r: w * 0.18 },
    { dx: w * 0.1, dy: -w * 0.1, r: w * 0.16 },
  ];
  return { x, y, w, h: w * 0.5, speed, puffs };
}

// Helper: create a row of flowers
function flowerRow(x: number, y: number, count: number, spacing = 60): Decoration[] {
  const flowers: Decoration[] = [];
  const colors = ['#FF6B9D', '#FFD93D', '#FF8C42', '#C490E4', '#FF5E7E'];
  for (let i = 0; i < count; i++) {
    flowers.push({
      x: x + i * spacing, y, w: 20, h: 30, type: 'flower',
      color: colors[i % colors.length], variant: i % 3,
    });
  }
  return flowers;
}

// Helper: create grass tufts
function grassRow(x: number, y: number, count: number, spacing = 45): Decoration[] {
  const grass: Decoration[] = [];
  for (let i = 0; i < count; i++) {
    grass.push({ x: x + i * spacing + Math.random() * 15, y, w: 16, h: 22, type: 'grass', variant: i % 3 });
  }
  return grass;
}

// Helper: create bushes
function bushRow(x: number, y: number, count: number, spacing = 120): Decoration[] {
  const bushes: Decoration[] = [];
  for (let i = 0; i < count; i++) {
    bushes.push({ x: x + i * spacing, y, w: 50, h: 40, type: 'bush', variant: i % 2 });
  }
  return bushes;
}

// Helper: create trees
function treeRow(x: number, y: number, count: number, spacing = 150, color = '#4CAF50'): Decoration[] {
  const trees: Decoration[] = [];
  for (let i = 0; i < count; i++) {
    trees.push({ x: x + i * spacing, y, w: 60, h: 100, type: 'tree', color, variant: i % 3 });
  }
  return trees;
}

